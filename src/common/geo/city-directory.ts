import cityRows from '../../assets/geonames/geonames-cities.json';

// Backs both the city-search endpoint (see discovery/city-search.service.ts)
// and the Group/Section geonameId/country/city/region identification check
// (see groups/dto/group-validation.helpers.ts#refineCityIdentification) -
// one shared dataset/index, never two, so "which cities can I search for"
// and "which city values are accepted on create/update" can never drift
// apart.
//
// Data source: official GeoNames export/dump files (CC BY 4.0 -
// https://download.geonames.org/export/dump/readme.txt), not the `cities.json`
// npm package this replaced - that package was a simplified re-export of the
// same underlying GeoNames data that dropped exactly the two things this
// module now needs: `geonameid` (a real, stable, GeoNames-assigned
// identifier - see getCityByGeonameId) and the `alternatenames` column (a
// flat, per-record list of name variants - see search() in
// city-search.service.ts). `assets/geonames/geonames-cities.json` (kept
// under a project-wide static-assets folder, not this module, since it is
// a build artifact rather than source code - see that folder's own
// README) is a *derived*, pre-processed dataset generated by
// `npm run geonames:build` (see build/generate-cities-dataset.ts for the
// exact two official files it reads and how) - never fetched at runtime,
// and never via the GeoNames Web API (api.geonames.org, a query-based,
// rate-limited service this project deliberately never depends on for a
// purely offline, zero-latency lookup).
//
// Local names / alternate names: GeoNames' own `alternatenames` column
// already includes local-language variants inline (e.g. geonameid 756135,
// Poland's capital, has `name="Warsaw"` but its `alternatenames` list
// includes "Warszawa" among ~70 variants) - confirmed directly against the
// raw dump. Per GeoNames' own readme: "If you don't need to know the
// language of a name variant, the field 'alternatenames' will be
// sufficient" - which matches this project's actual requirement exactly:
// searching "Warszawa" or "Warsaw" must resolve to the *same* geonameId,
// not necessarily display a "preferred" localized name (the `name` field
// stays whatever GeoNames itself considers this record's canonical name -
// still "Warsaw" for this one). Resolving *that* separate, narrower
// question (which single name to prefer for display) would need the
// language-tagged `alternateNamesV2` dataset instead, which is far larger
// (~202 MB compressed worldwide) - not needed here and not fetched.
export interface CityRecord {
  geonameId: number;
  name: string;
  // Every other name GeoNames records for this place - used only for
  // search matching (see city-search.service.ts), never returned as a
  // stand-in for `name`, and never validated against on create/update
  // (see refineCityIdentification - `city` must equal `name` exactly).
  alternateNames: readonly string[];
  country: string;
  // The admin1 division's human-readable (English) name, e.g. "Mazovia" -
  // resolved once at build time (see generate-cities-dataset.ts), `null`
  // when the source has no admin1 code for this city, or no matching
  // admin1CodesASCII.txt entry.
  region: string | null;
}

interface CityIndexes {
  byCountry: Map<string, CityRecord[]>;
  byGeonameId: Map<number, CityRecord>;
}

// Built once per process, lazily on first use, not at module load - so
// importing this module (e.g. transitively, from a Zod schema file that
// may be loaded before it is ever actually needed) never pays the ~170k-row
// indexing cost unless a request actually requires it.
let indexes: CityIndexes | null = null;

function buildIndexes(): CityIndexes {
  const byCountry = new Map<string, CityRecord[]>();
  const byGeonameId = new Map<number, CityRecord>();

  for (const row of cityRows as CityRecord[]) {
    byGeonameId.set(row.geonameId, row);

    const list = byCountry.get(row.country);
    if (list) {
      list.push(row);
    } else {
      byCountry.set(row.country, [row]);
    }
  }

  return { byCountry, byGeonameId };
}

function getIndexes(): CityIndexes {
  if (!indexes) {
    indexes = buildIndexes();
  }
  return indexes;
}

/**
 * Every known city for `countryCode` (an ISO 3166-1 alpha-2 code, expected
 * already-uppercased - see countryCodeSchema), in no particular order - see
 * CitySearchService for sorting/filtering/limiting. Empty array for a
 * country with no rows in the dataset (never thrown - an unrecognized or
 * obscure country code is simply "no cities", the same shape as a query
 * that legitimately matches nothing).
 */
export function getCitiesForCountry(
  countryCode: string,
): readonly CityRecord[] {
  return getIndexes().byCountry.get(countryCode) ?? [];
}

/**
 * The one record `geonameId` refers to, or `undefined` if it does not
 * exist in the bundled dataset. `geonameId` is the GeoNames-assigned,
 * globally stable identifier for a place - unlike `country`+`city`+`region`
 * (kept only for display/compatibility/filtering - see group.entity.ts),
 * this alone is enough to name one exact real-world place, so it is the
 * single source of truth the Group/Section create/update validation
 * resolves against (see group-validation.helpers.ts#refineCityIdentification).
 */
export function getCityByGeonameId(geonameId: number): CityRecord | undefined {
  return getIndexes().byGeonameId.get(geonameId);
}
